# Import required libraries

import networkx as nx
import matplotlib.pyplot as plt
# Create a directed graph

G = nx.DiGraph()

# Create waiting relationships between transactions
# T1 waits for T2
# T2 waits for T3
# T3 waits for T1

edges = [
    ("T1", "T2"),
    ("T2", "T3"),
    ("T3", "T1")
]

G.add_edges_from(edges)

# Draw the wait-for graph

plt.figure(figsize=(5, 4))

nx.draw(
    G,
    with_labels=True,
    node_size=2000,
    font_size=12,
    arrows=True
)

plt.title("Deadlock Wait-For Graph")

plt.show()

# Detect circular waiting

try:

    cycle = nx.find_cycle(G)

    print("DEADLOCK DETECTED!")

    print("Circular waiting:", cycle)

except nx.NetworkXNoCycle:

    print("No Deadlock Detected")

