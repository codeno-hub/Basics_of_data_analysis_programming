# PRACTICAL 2: TWO-PHASE LOCKING (2PL)
# ============================================================
print("PRACTICAL 2: TWO-PHASE LOCKING")
# Create a transaction schedule

schedule = [
    "Lock(A)",
    "Lock(B)",
    "Lock(C)",
    "Unlock(A)",
    "Unlock(B)",
    "Unlock(C)"
]

print("\nTransaction Schedule:")
for step in schedule:
    print(step)
# Check whether the schedule follows 2PL

unlock_started = False
valid = True

for step in schedule:

    # Check if an unlock operation has started

    if "Unlock" in step:
        unlock_started = True

    # No new lock is allowed after unlocking starts

    if "Lock" in step and unlock_started:
        valid = False

print("\nIs this a valid 2PL schedule?")

if valid:
    print("YES - Valid Two-Phase Locking")
else:
    print("NO - 2PL Rule Violated")

